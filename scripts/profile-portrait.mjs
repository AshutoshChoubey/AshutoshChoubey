const shades = ['#361427', '#54253A', '#701A3D', '#945570', '#C77B9B', '#D797B1', '#E5B5C7', '#F8F0F3'];
const dots = shades.map(() => []);
for (const [y, row] of rows.entries()) {
  for (const [x, level] of [...row].entries()) {
    if (level !== ' ') dots[Number(level)].push(`M${x} ${y}h.01`);
  }
}

export function renderDotPortrait(x, y, scale) {
  const paths = dots.map((marks, level) => `<path d="${marks.join('')}" stroke="${shades[level]}" stroke-width="${(0.48 + level * 0.068).toFixed(2)}"/>`);
  return `<g transform="translate(${x} ${y}) scale(${scale})" stroke-linecap="round" fill="none">${paths.join('')}</g>`;
}
